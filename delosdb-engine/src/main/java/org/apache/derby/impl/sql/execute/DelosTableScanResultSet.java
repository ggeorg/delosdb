    private DelosTableScanResultSet(
            TableScanResultSetParameters params,
            DelosTableScanProviderLookup.Result providerLookup,
            boolean nativeSelectEquality,
            boolean nativeSelectAll,
            boolean nativeOrPredicateResidual)
    {
        super(params.activation,
                params.resultSetNumber,
                params.optimizerEstimatedRowCount,
                params.optimizerEstimatedCost);
        this.params = params;
        this.providerLookup = providerLookup;
        this.nativeSelectEquality = nativeSelectEquality;
        this.nativeSelectAll = nativeSelectAll;
        this.nativeOrPredicateResidual = nativeOrPredicateResidual;
        recordConstructorTime();
    }

    static Optional<NoPutResultSet> createIfEnabled(TableScanResultSetParameters params)
            throws StandardException
    {
        boolean nativeSelectAllEnabled = Boolean.getBoolean(NATIVE_SELECT_ALL_PROPERTY)
                || Boolean.getBoolean(NATIVE_COUNT_AGGREGATE_PROPERTY);
        boolean nativeOrPredicateEnabled = Boolean.getBoolean(NATIVE_OR_PREDICATES_PROPERTY);
        boolean nativeProjectionVariantsEnabled = Boolean.getBoolean(NATIVE_PROJECTION_VARIANTS_PROPERTY);
        boolean nativeOrderByResidualEnabled = Boolean.getBoolean(NATIVE_ORDER_BY_RESIDUAL_PROPERTY);
        boolean nativeFullScanEnabled = nativeSelectAllEnabled
                || nativeOrPredicateEnabled
                || nativeProjectionVariantsEnabled
                || nativeOrderByResidualEnabled;
        boolean nativePredicateScanEnabled = nativeFullScanEnabled
                || Boolean.getBoolean(NATIVE_SELECT_EQUALITY_PROPERTY)
                || Boolean.getBoolean(NATIVE_RANGE_PREDICATES_PROPERTY)
                || Boolean.getBoolean(NATIVE_BETWEEN_PREDICATES_PROPERTY)
                || Boolean.getBoolean(NATIVE_NULL_PREDICATES_PROPERTY);
        boolean skeletonEnabled = Boolean.getBoolean(SKELETON_BRANCH_PROPERTY);
        boolean nativeProviderFullScan = isUnqualifiedFullScan(params.qualifiers);
        if (!nativePredicateScanEnabled && !skeletonEnabled && !nativeProviderFullScan) {
            return Optional.empty();
        }

        Optional<DelosTableScanProviderLookup.Result> lookup =
                DelosTableScanProviderLookup.find(params.activation, params.tableName);
        if (lookup.isEmpty() || lookup.get().isDefaultStorageProvider()) {
            return Optional.empty();
        }

        if (nativeProviderFullScan && !nativePredicateScanEnabled && !skeletonEnabled) {
            return Optional.of(new DelosTableScanResultSet(
                    params,
                    lookup.get(),
                    true,
                    true,
                    false));
        }

        return Optional.of(new DelosTableScanResultSet(
                params,
                lookup.get(),
                nativePredicateScanEnabled,
                nativeFullScanEnabled,
                nativeOrPredicateEnabled));
    }

    private static boolean isUnqualifiedFullScan(Qualifier[][] qualifiers)
    {
        if (qualifiers == null || qualifiers.length == 0) {
            return true;
        }
        for (Qualifier[] termQualifiers : qualifiers) {
            if (termQualifiers != null && termQualifiers.length > 0) {
                return false;
            }
        }
        return true;
    }

    @Override
    public void openCore() throws StandardException
    {
        beginTime = getCurrentTimeMillis();
        try {
            if (isOpen) {
                throw StandardException.plainWrapException(
                        new IllegalStateException("DelosTableScanResultSet is already open"));
            }
            if (!nativeSelectEquality) {
                throw StandardException.plainWrapException(
                        new UnsupportedOperationException(SKELETON_REACHED_MESSAGE));
            }

            TableDescriptor tableDescriptor = tableDescriptor();
            scanTableDescriptor = tableDescriptor;
            accessedCols = accessedColumnsForNativeScan();
            List<DelosPredicate> filters = scanPredicates(tableDescriptor, nativeSelectAll);
            nativeAccess = DelosNativeResultSetSupport.openNativeTableAccess(params.activation, tableDescriptor, providerLookup);
            requireSnapshotIsolation(nativeAccess.tableAccess());
            scan = nativeAccess.tableAccess().scan(
                    nativeAccess.context(),
                    filters,
                    DelosProjection.all());
            isOpen = true;
            finished = false;
            numOpens++;
        } catch (SQLException e) {
            abortNativeAccess(e);
            throw StandardException.plainWrapException(e);
        } catch (RuntimeException e) {
            abortNativeAccess(e);
            throw StandardException.plainWrapException(e);
        } catch (StandardException e) {
            abortNativeAccess(e);
            throw e;
        } finally {
            openTime += getElapsedMillis(beginTime);
        }
    }

    @Override
    public ExecRow getNextRowCore() throws StandardException
    {
        beginTime = getCurrentTimeMillis();
        try {
            if (!isOpen || scan == null) {
                return null;
            }
            while (scan.next()) {
                currentDelosRow = scan.row();
                if (!matchesLocalOrQualifierGroups(currentDelosRow)) {
                    continue;
                }

                ExecRow candidate = newResultRow();
                materializeBaseRow(currentDelosRow, candidate);
                ExecRow row = compactNativeRow(candidate);
                rowsSeen++;
                setCurrentRow(row);
                return row;
            }

            currentDelosRow = null;
            clearCurrentRow();
            finished = true;
            return null;
        } finally {
            nextTime += getElapsedMillis(beginTime);
        }
    }

    @Override
    public void close() throws StandardException
    {
        beginTime = getCurrentTimeMillis();
        StandardException failure = null;
        try {
            if (scan != null) {
                try {
                    scan.close();
                } catch (RuntimeException e) {
                    failure = StandardException.plainWrapException(e);
                } finally {
                    scan = null;
                }
            }
            if (nativeAccess != null) {
                try {
                    nativeAccess.close();
                } catch (SQLException e) {
                    StandardException wrapped = StandardException.plainWrapException(e);
                    if (failure == null) {
                        failure = wrapped;
                    } else {
                        failure.addSuppressed(wrapped);
                    }
                } finally {
                    nativeAccess = null;
                }
            }
            scanTableDescriptor = null;
            accessedCols = null;
            currentDelosRow = null;
            clearCurrentRow();
            super.close();
        } finally {
            closeTime += getElapsedMillis(beginTime);
        }
        if (failure != null) {
            throw failure;
        }
    }

    @Override
    public long getTimeSpent(int type)
    {
        return constructorTime + openTime + nextTime + closeTime;
    }

    @Override
    public int getScanIsolationLevel()
    {
        return params.isolationLevel;
    }

